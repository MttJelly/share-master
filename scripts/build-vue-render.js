const fs = require("node:fs");
const path = require("node:path");
const { compile } = require("@vue/compiler-dom");

const root = path.resolve(__dirname, "..");
const sourceFile = path.join(root, "src", "renderer", "index.html");
const outputFile = path.join(root, "src", "renderer", "vue-render.generated.js");
const source = fs.readFileSync(sourceFile, "utf8");
const startMarker = "<!-- VUE_TEMPLATE_START -->";
const endMarker = "<!-- VUE_TEMPLATE_END -->";
const start = source.indexOf(startMarker);
const end = source.indexOf(endMarker);

if (start < 0 || end < 0 || end <= start) {
  throw new Error("Vue template markers are missing or invalid in src/renderer/index.html.");
}

const template = source.slice(start + startMarker.length, end).trim();
const { code } = compile(template, {
  mode: "module",
  prefixIdentifiers: true,
  hoistStatic: true,
  runtimeModuleName: "../../node_modules/vue/dist/vue.runtime.esm-browser.prod.js",
});
const output = `// Generated by scripts/build-vue-render.js. Do not edit directly.\n${code}\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, "utf8") : "";
  if (current !== output) {
    throw new Error("Vue renderer is stale. Run npm run build:renderer.");
  }
} else {
  fs.writeFileSync(outputFile, output, "utf8");
}
